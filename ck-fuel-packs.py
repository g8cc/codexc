def validate_profile(value):
    if not isinstance(value, dict) or type(value.get('version')) is not int or value['version'] != 1:
        raise ValueError('fuel profile must be a version 1 object')
    enabled = value.get('enabled')
    if (not isinstance(enabled, list) or len(enabled) > len(PACKS)
            or any(not isinstance(name, str) or name not in PACKS for name in enabled)
            or len(set(enabled)) != len(enabled)):
        raise ValueError('fuel profile enabled must contain distinct known pack IDs')
    return enabled
